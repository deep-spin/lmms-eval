def blink_doc_to_text(doc, need_disclaimer: bool = False):
    """
    Constructs the textual input for the LMM from a BLINK document.
    Combines the 'question' and 'prompt' fields and lists the multiple-choice options.
    """
    prompt = doc['prompt']
    if need_disclaimer:
        prompt = disclaimer + prompt
    prompt += ". The last line of your response should be of the following format: 'Answer: $LETTER' (without quotes) where LETTER is one of options. Think step by step before answering."
    return prompt 

def blink_doc_to_target(doc):
    """
    Extracts the ground truth answer from a BLINK document.
    """
    # The target is the correct answer from the choices.
    return doc['answer']

def blink_doc_to_visual(doc):
    """
    Loads and prepares images associated with a BLINK document.
    Handles multiple image columns (image_1, image_2, image_3, image_4).
    """
    image_paths = []
    for k in ['image_1', 'image_2', 'image_3', 'image_4']:
        if k in doc and doc[k]:
            img = doc[k]
            if img:
                image_paths.append(img)

    return image_paths if image_paths else None # Return list of PIL Images or None

