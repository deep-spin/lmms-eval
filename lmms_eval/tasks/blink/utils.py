# Helper function to load image from bytes if necessary, or return PIL Image directly
def _load_image(image_data):
    """
    Loads an image from various formats provided by the Hugging Face datasets library.
    Assumes image_data can be a dictionary with 'bytes' key or a PIL Image object.
    """
    if isinstance(image_data, dict) and 'bytes' in image_data:
        return Image.open(io.BytesIO(image_data['bytes']))
    elif isinstance(image_data, Image.Image):
        return image_data
    return None # Return None for unsupported formats or missing data

