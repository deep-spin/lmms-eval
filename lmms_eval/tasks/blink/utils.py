def blink_aggregation(results):
    """
    Computes accuracy and number of examples from a list of result dictionaries.
    
    Each dictionary should have at least:
    - 'answer': the ground truth
    - 'parsed_pred': the model prediction

    Args:
        results (list of dict): List of prediction results.

    Returns:
        dict: A dictionary with 'accuracy' and 'num_examples'.
    """
    if not results:
        return {'accuracy': 0.0, 'num_examples': 0}

    correct = 0
    for entry in results:
        if entry['parsed_pred'] == entry['answer']:
            correct += 1

    num_examples = len(results)
    accuracy = correct / num_examples

    print("Number of examples:", num_examples, "Accuracy:", accuracy)
    return accuracy